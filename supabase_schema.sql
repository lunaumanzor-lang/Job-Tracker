-- ==============================================================================
-- JOB TRACKER - ESQUEMA INTEGRAL SUPABASE (MULTI-USUARIO CON RLS ESTRICTO)
-- ==============================================================================

-- 1. TABLA: applications (Asegurar existencia y agregar recruiter)
CREATE TABLE IF NOT EXISTS public.applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    company TEXT NOT NULL,
    position TEXT NOT NULL,
    application_date DATE,
    status TEXT NOT NULL DEFAULT 'Applied',
    salary TEXT,
    work_mode TEXT DEFAULT 'TBD',
    location TEXT,
    job_url TEXT,
    notes TEXT,
    follow_up_date DATE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.applications ADD COLUMN IF NOT EXISTS recruiter TEXT;

-- 2. TABLA: interviews
CREATE TABLE IF NOT EXISTS public.interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    application_id BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    date TIMESTAMPTZ NOT NULL,
    interview_type TEXT NOT NULL,
    notes TEXT,
    result TEXT DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. TABLA: skills (Requeridas por oferta laboral)
CREATE TABLE IF NOT EXISTS public.skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    application_id BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    skill TEXT NOT NULL,
    match_status TEXT DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. TABLA: user_profile (Perfil profesional maestro)
CREATE TABLE IF NOT EXISTS public.user_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    full_name TEXT,
    current_title TEXT,
    email TEXT,
    phone TEXT,
    location TEXT,
    summary TEXT,
    preferred_language TEXT DEFAULT 'es',
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. TABLA: user_skills (Habilidades en My Profile)
CREATE TABLE IF NOT EXISTS public.user_skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    skill_name TEXT NOT NULL,
    category TEXT NOT NULL,
    source TEXT DEFAULT 'Manual',
    proficiency TEXT DEFAULT 'Intermediate',
    date_added DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. TABLA: experience_entries (CV Builder)
CREATE TABLE IF NOT EXISTS public.experience_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    company TEXT NOT NULL,
    position TEXT NOT NULL,
    start_date TEXT,
    end_date TEXT,
    is_current BOOLEAN DEFAULT FALSE,
    order_index INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. TABLA: resume_bullets (Logros de experiencia)
CREATE TABLE IF NOT EXISTS public.resume_bullets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    experience_id BIGINT NOT NULL REFERENCES public.experience_entries(id) ON DELETE CASCADE,
    bullet_text TEXT NOT NULL,
    original_text TEXT NOT NULL,
    current_text TEXT NOT NULL,
    order_index INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. TABLA: education_entries (CV Builder)
CREATE TABLE IF NOT EXISTS public.education_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    institution TEXT NOT NULL,
    credential TEXT NOT NULL,
    start_date TEXT,
    end_date TEXT,
    order_index INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- ÍNDICES DE RENDIMIENTO (user_id y claves foráneas)
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_applications_user_id ON public.applications (user_id);
CREATE INDEX IF NOT EXISTS idx_interviews_user_id ON public.interviews (user_id);
CREATE INDEX IF NOT EXISTS idx_interviews_application_id ON public.interviews (application_id);
CREATE INDEX IF NOT EXISTS idx_skills_user_id ON public.skills (user_id);
CREATE INDEX IF NOT EXISTS idx_skills_application_id ON public.skills (application_id);
CREATE INDEX IF NOT EXISTS idx_user_profile_user_id ON public.user_profile (user_id);
CREATE INDEX IF NOT EXISTS idx_user_skills_user_id ON public.user_skills (user_id);
CREATE INDEX IF NOT EXISTS idx_experience_entries_user_id ON public.experience_entries (user_id);
CREATE INDEX IF NOT EXISTS idx_resume_bullets_user_id ON public.resume_bullets (user_id);
CREATE INDEX IF NOT EXISTS idx_resume_bullets_experience_id ON public.resume_bullets (experience_id);
CREATE INDEX IF NOT EXISTS idx_education_entries_user_id ON public.education_entries (user_id);

