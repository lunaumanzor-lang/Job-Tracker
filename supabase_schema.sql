-- ==============================================================================
-- LIMPIEZA DINÁMICA DE POLÍTICAS EXISTENTES EN applications
-- (Elimina automáticamente cualquier política previa sin necesitar sus nombres)
-- ==============================================================================
DO $$
DECLARE
    pol RECORD;
BEGIN
    FOR pol IN
        SELECT policyname
        FROM pg_policies
        WHERE schemaname = 'public' AND tablename = 'applications'
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.applications;', pol.policyname);
    END LOOP;
END $$;

-- Eliminar políticas previas conocidas en las otras tablas (si existían)
DROP POLICY IF EXISTS "interviews_user_policy" ON public.interviews;
DROP POLICY IF EXISTS "skills_user_policy" ON public.skills;
DROP POLICY IF EXISTS "user_profile_user_policy" ON public.user_profile;
DROP POLICY IF EXISTS "user_skills_user_policy" ON public.user_skills;
DROP POLICY IF EXISTS "experience_entries_user_policy" ON public.experience_entries;
DROP POLICY IF EXISTS "resume_bullets_user_policy" ON public.resume_bullets;
DROP POLICY IF EXISTS "education_entries_user_policy" ON public.education_entries;

-- ==============================================================================
-- CREACIÓN DE POLÍTICAS RLS OPTIMIZADAS CON (SELECT auth.uid()) Y VERIFICACIÓN EXISTS
-- ==============================================================================

-- 1. applications
CREATE POLICY "applications_user_policy" ON public.applications
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));

-- 2. interviews (Verifica que la postulación padre pertenezca al usuario)
CREATE POLICY "interviews_user_policy" ON public.interviews
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (
        user_id = (SELECT auth.uid()) AND
        EXISTS (
            SELECT 1 FROM public.applications a
            WHERE a.id = interviews.application_id AND a.user_id = (SELECT auth.uid())
        )
    );

-- 3. skills (Verifica que la postulación padre pertenezca al usuario)
CREATE POLICY "skills_user_policy" ON public.skills
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (
        user_id = (SELECT auth.uid()) AND
        EXISTS (
            SELECT 1 FROM public.applications a
            WHERE a.id = skills.application_id AND a.user_id = (SELECT auth.uid())
        )
    );

-- 4. user_profile
CREATE POLICY "user_profile_user_policy" ON public.user_profile
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));

-- 5. user_skills
CREATE POLICY "user_skills_user_policy" ON public.user_skills
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));

-- 6. experience_entries
CREATE POLICY "experience_entries_user_policy" ON public.experience_entries
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));

-- 7. resume_bullets (Verifica que la experiencia laboral padre pertenezca al usuario)
CREATE POLICY "resume_bullets_user_policy" ON public.resume_bullets
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (
        user_id = (SELECT auth.uid()) AND
        EXISTS (
            SELECT 1 FROM public.experience_entries e
            WHERE e.id = resume_bullets.experience_id AND e.user_id = (SELECT auth.uid())
        )
    );

-- 8. education_entries
CREATE POLICY "education_entries_user_policy" ON public.education_entries
    FOR ALL TO authenticated
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));
