def get_current_language() -> str:
    """
    Retorna el código de idioma activo ('es' o 'en') almacenado en st.session_state.
    Si aún no ha sido inicializado o se corre fuera de contexto, retorna 'es'.
    """
    try:
        if hasattr(st, "session_state") and "lang" in st.session_state:
            return st.session_state["lang"]
    except Exception:
        pass
    return "es"


def t(key: str, lang: Optional[str] = None, **kwargs: Any) -> str:
    """
    Función de traducción centralizada:
    1. Resuelve el idioma objetivo (el provisto, o el de st.session_state['lang'], o 'es').
    2. Busca la cadena en TRANSLATIONS[target_lang].
    3. Si no existe, recurre a 'es' como fallback.
    4. Si tampoco existe en 'es', devuelve la clave cruda (para facilitar debugging).
    5. Si se pasan kwargs, interpola variables usando .format(**kwargs).
    """
    target_lang = lang or get_current_language()
    if target_lang not in TRANSLATIONS:
        target_lang = "es"

    # Buscar en el idioma objetivo, o fallback a español, o la clave
    template = TRANSLATIONS[target_lang].get(key)
    if template is None:
        template = TRANSLATIONS["es"].get(key, key)

    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template

    return template


def t_status(status_val: str, lang: Optional[str] = None) -> str:
    """
    Fase 6.2: Traduce exclusivamente la etiqueta de presentación de un estado.
    - Si el término pertenece a NEVER_TRANSLATE (ej. 'Ghosted'), se devuelve tal cual en inglés.
    - Si no existe traducción en el diccionario, se devuelve el valor original.
    """
    if not status_val or status_val in NEVER_TRANSLATE:
        return status_val
    return t(status_val, lang=lang)


def t_work_mode(mode_val: str, lang: Optional[str] = None) -> str:
    """
    Traduce exclusivamente la etiqueta de presentación de la modalidad de trabajo.
    """
    if not mode_val:
        return mode_val
    target_lang = lang or get_current_language()
    if target_lang == "es":
        mapping = {
            "Remote": "Remoto",
            "Hybrid": "Híbrido",
            "On-site": "Presencial",
            "TBD": "Por definir"
        }
        return mapping.get(mode_val, mode_val)
    return mode_val

